"""
    swap_null(Y, [n_trades]; rng=Random.default_rng())

A random presence/absence matrix with the same number of species at every site (row totals)
and the same prevalence for every species (column totals) as `Y`, but no associations beyond
those the totals impose. Generated by the curveball algorithm (Strona et al. 2014): in each
trade two sites exchange a random subset of the species that only one of them holds.

Use it to check an analysis: fitted to such matrices, a sound analysis should find few
associations. The default `n_trades` is `10 * max(N, S)` for an `N × S` matrix.
"""
function swap_null(Y::AbstractMatrix, n_trades::Integer=10 * max(size(Y)...);
                   rng::Random.AbstractRNG=Random.default_rng())
    P = Y .> 0
    N = size(P, 1)
    rows = [findall(view(P, n, :)) for n in 1:N]
    if N >= 2
        for _ in 1:n_trades
            a, b = rand(rng, 1:N), rand(rng, 1:N - 1)
            b >= a && (b += 1)
            only_a = setdiff(rows[a], rows[b])
            only_b = setdiff(rows[b], rows[a])
            (isempty(only_a) || isempty(only_b)) && continue
            pool = Random.shuffle!(rng, vcat(only_a, only_b))
            shared = intersect(rows[a], rows[b])
            rows[a] = vcat(shared, pool[1:length(only_a)])
            rows[b] = vcat(shared, pool[length(only_a)+1:end])
        end
    end
    Z = falses(size(P))
    for n in 1:N
        Z[n, rows[n]] .= true
    end
    return Z
end
